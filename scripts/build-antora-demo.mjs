import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'
import { samples } from '../site/lib/gallery-samples.js'
import { DEFAULT_RENDERERS } from '../src/browser.js'

const root = fileURLToPath(new URL('..', import.meta.url))
const demo = path.join(root, 'examples/antora-demo')
const partials = path.join(demo, 'docs/modules/ROOT/partials')
await fs.mkdir(partials, { recursive: true })
const gallery = [...samples]
for (const [type, original] of [['dot', 'graphviz'], ['c4plantuml', 'plantuml']]) {
  const sample = samples.find((sample) => sample.type === original)
  gallery.push({ ...sample, type, title: `${type} (${original} alias)` })
}
for (const type of Object.keys(DEFAULT_RENDERERS)) {
  if (!gallery.some((sample) => sample.type === type)) throw new Error(`Missing demo sample: ${type}`)
}
await fs.writeFile(path.join(partials, 'diagram-gallery.adoc'), '// Generated by scripts/build-antora-demo.mjs\n\n' + gallery.map(({ type, title, source }) =>
  `=== ${title}\n\n[${type}]\n----\n${source}\n----\n\n.Source (${type})\n[%collapsible]\n====\n[source,text]\n----\n${source}\n----\n====\n`
).join('\n'))

// Remove stale hashed assets when renderer dependencies change.
await fs.rm(path.join(demo, 'supplemental-ui/js'), { recursive: true, force: true })
await build({
  stdin: {
    contents: `import { hydrateLocalDiagrams } from './site/lib/local-renderers.js';\nimport './src/style.css';\nhydrateLocalDiagrams(document).catch(console.error);`,
    resolveDir: root,
  },
  bundle: true,
  format: 'esm',
  outdir: path.join(demo, 'supplemental-ui/js'),
  entryNames: 'diagrams',
  assetNames: '[name]-[hash]',
  minify: true,
  plugins: [{
    name: 'local-renderer-assets',
    setup(build) {
      // These imports belong to unused Node-only branches of browser libraries.
      build.onResolve({ filter: /^(node:fs|fs|path)$/ }, (args) => ({ path: args.path, namespace: 'browser-unused' }))
      build.onLoad({ filter: /.*/, namespace: 'browser-unused' }, () => ({ contents: 'export default {}' }))
      build.onResolve({ filter: /\?url/ }, (args) => ({
        path: import.meta.resolve(args.path.split('?')[0]),
        namespace: args.path.includes('inline') ? 'inline-asset' : 'script-asset',
      }))
      build.onLoad({ filter: /.*/, namespace: 'inline-asset' }, async ({ path: url }) => ({
        contents: await fs.readFile(fileURLToPath(url)), loader: 'dataurl',
      }))
      build.onLoad({ filter: /.*/, namespace: 'script-asset' }, async ({ path: url }) => ({
        contents: await fs.readFile(fileURLToPath(url)), loader: 'file',
      }))
    },
  }],
})
